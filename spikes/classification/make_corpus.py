def write_pdf(name, pages, truth):
    """pages: רשימת רשימות-שורות; כל אחת עמוד נפרד."""
    html = "".join(base.to_html(lines).split("<body>")[1].split("</body>")[0]
                   + '<div style="page-break-after:always"></div>' for lines in pages)
    head = base.to_html(pages[0]).split("<body>")[0]
    path = OUT / (name + ".html")
    path.write_text(head + "<body>" + html + "</body></html>", encoding="utf-8")
    base.print_pdf(path, OUT / (name + ".pdf"))
    (OUT / (name + ".truth.json")).write_text(json.dumps(dict(truth, synthetic=True,
        text="\n".join(base.plain_text(l) for l in pages)), ensure_ascii=False), encoding="utf-8")


def write_scan(name):
    """PDF של תמונות 300dpi - כמו מסמך שנסרק במכונת משרד."""
    import pypdfium2 as pdfium
    pdf = pdfium.PdfDocument(str(OUT / (name + ".pdf")))
    images = [pdf[i].render(scale=300 / 72).to_pil().convert("L") for i in range(len(pdf))]
    pdf.close()
    images[0].save(OUT / (name + ".scan.pdf"), save_all=True, append_images=images[1:],
                   resolution=300)


